#!/usr/bin/env node
// Generates fixed Material 3 Tonal Spot schemes with Google's color utilities.
// npm install --prefix /tmp/pathpilot-colors @material/material-color-utilities@0.3.0
// node scripts/generate-theme-palettes.mjs /tmp/pathpilot-colors/node_modules/@material/material-color-utilities/index.js > app/src/main/java/dev/pathpilot/app/ui/theme/GeneratedThemePalettes.kt
import {readFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {pathToFileURL} from 'node:url';

const modulePath = resolve(process.argv[2]);
const metadata = JSON.parse(readFileSync(join(dirname(modulePath), 'package.json'), 'utf8'));
if (metadata.version !== '0.3.0') throw new Error('Use @material/material-color-utilities@0.3.0');
const {Contrast, Hct, SchemeTonalSpot, lstarFromArgb} = await import(pathToFileURL(modulePath));
const seeds = {OCEAN: 0xff0061a4, VIOLET: 0xff6750a4, ROSE: 0xffb24c63, AMBER: 0xff8d6e00};
const paletteName = name => name[0] + name.slice(1).toLowerCase();
const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface', 'error', 'onError', 'errorContainer',
  'onErrorContainer', 'outline', 'outlineVariant', 'scrim', 'surfaceBright', 'surfaceDim',
  'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh',
  'surfaceContainerHighest', 'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed',
  'onPrimaryFixedVariant', 'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed',
  'onSecondaryFixedVariant', 'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed',
  'onTertiaryFixedVariant',
];
const lines = [
  '// Generated by scripts/generate-theme-palettes.mjs; do not edit color values by hand.',
  '// Source: https://github.com/material-foundation/material-color-utilities (npm 0.3.0).',
  '// SchemeTonalSpot, contrast level 0.0. Forest retains PathPilot\'s original palette.',
  'package dev.pathpilot.app.ui.theme', '',
  'import androidx.compose.material3.ColorScheme',
  'import androidx.compose.material3.darkColorScheme',
  'import androidx.compose.material3.lightColorScheme',
  'import androidx.compose.ui.graphics.Color',
  'import dev.pathpilot.app.settings.ThemePalette', '',
  'internal fun presetColorScheme(palette: ThemePalette, dark: Boolean): ColorScheme = when (palette) {',
  '    ThemePalette.FOREST -> if (dark) ForestDarkColors else ForestLightColors',
  ...Object.keys(seeds).map(name => `    ThemePalette.${name} -> if (dark) ${paletteName(name)}Dark else ${paletteName(name)}Light`),
  '}', '',
];
for (const [name, seed] of Object.entries(seeds)) {
  lines.push(`// Seed: 0x${seed.toString(16).toUpperCase()}`);
  for (const dark of [false, true]) {
    const scheme = new SchemeTonalSpot(Hct.fromInt(seed), dark, 0.0);
    for (const role of ['primary', 'primaryContainer', 'secondary', 'secondaryContainer',
      'tertiary', 'tertiaryContainer', 'background', 'surface', 'error', 'errorContainer']) {
      const foreground = `on${role[0].toUpperCase()}${role.slice(1)}`;
      const ratio = Contrast.ratioOfTones(lstarFromArgb(scheme[role]), lstarFromArgb(scheme[foreground]));
      if (ratio < 4.5) throw new Error(`${name}/${dark}/${role}: text contrast ${ratio} < 4.5`);
    }
    lines.push(`private val ${paletteName(name)}${dark ? 'Dark' : 'Light'} = ${dark ? 'dark' : 'light'}ColorScheme(`);
    for (const role of roles) {
      const value = scheme[role];
      if (typeof value !== 'number') throw new Error(`Missing color role: ${role}`);
      lines.push(`    ${role} = Color(0x${(value >>> 0).toString(16).toUpperCase().padStart(8, '0')}),`);
    }
    lines.push(')', '');
  }
}
process.stdout.write(lines.join('\n'));
