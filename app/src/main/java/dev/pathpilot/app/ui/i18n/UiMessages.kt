/** Translate known application messages at the UI boundary, preserving unknown upstream errors. */
fun Resources.localize(message: String): String {
    knownMessages[message]?.let { return getString(it) }
    for ((pattern, resource) in messagePatterns) {
        val match = pattern.matchEntire(message) ?: continue
        return getString(resource, *match.groupValues.drop(1).toTypedArray())
    }
    return message
}

fun Resources.tokenCount(value: Long?): String = value?.let {
    NumberFormat.getIntegerInstance(configuration.locales[0]).format(it)
} ?: getString(R.string.ui_unavailable)

internal fun Resources.rangeLabel(range: UsageRange): String = getString(when (range) {
    UsageRange.TODAY -> R.string.ui_today
    UsageRange.LAST_7_DAYS -> R.string.ui_7_days
    UsageRange.LAST_30_DAYS -> R.string.ui_30_days
    UsageRange.ALL -> R.string.ui_all
})

fun Resources.outcomeLabel(outcome: RequestOutcome): String = getString(when (outcome) {
    RequestOutcome.SUCCESS -> R.string.ui_success
    RequestOutcome.HTTP_ERROR -> R.string.ui_failed
    RequestOutcome.INTERRUPTED -> R.string.ui_interrupted
})

